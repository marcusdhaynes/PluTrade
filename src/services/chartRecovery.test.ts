import assert from 'node:assert/strict';
import {INITIAL_ASSETS} from '../data/assets';
import {chartStarterMarket,recoveryMarkets,chartEmptyExplanation,canOfferPublicHistory} from './chartRecovery';
const chosen=chartStarterMarket(INITIAL_ASSETS);
assert.equal(chosen.symbol,'BTCUSD');
assert.equal(chosen.source,'Coinbase');
assert.equal(chosen.marketType,'spot');
assert.equal(chartStarterMarket([INITIAL_ASSETS[0]]).symbol,'PF_ARBUSD');
const candidates=recoveryMarkets(INITIAL_ASSETS,chosen);
assert.ok(candidates.some(c=>c.symbol==='ETHUSD'&&c.source==='Coinbase'));
assert.ok(candidates.every(c=>c.marketType==='spot'));
assert.ok(candidates.every(c=>c.symbol!==chosen.symbol||c.source!==chosen.source));
assert.ok(candidates.length<=5);
assert.equal(canOfferPublicHistory(chosen),true);
assert.match(chartEmptyExplanation(INITIAL_ASSETS[0],'1s','empty'),/no supported native/);
assert.match(chartEmptyExplanation(chosen,'1m','empty'),/No verified/);
assert.match(chartEmptyExplanation(chosen,'1m','error'),/request failed/);
assert.match(chartEmptyExplanation(chosen,'1m','loading'),/Loading genuine/);
console.log('Chart recovery chooses sourced spot history on fresh installs and does not fabricate candles.');
